export function mountMaterialChart(svg, id) {
  const registration = materialChartRegistration[id];
  if (!registration) return null;
  const parent = svg.querySelector('.swatch')?.parentElement;
  const nodes = [...(parent?.children || [])];
  // All 21 pinned grid plates have four heading nodes, then 49 swatches,
  // their outer frame and 12 axis labels, followed by three footer nodes.
  // Fail closed if an asset changes structure; never guess which text to move.
  if (nodes.length !== 69 || nodes.slice(0,4).some(n => n.localName !== 'text') || nodes.slice(-3).some(n => n.localName !== 'text') || nodes.slice(4,53).some(n => !n.classList.contains('swatch')) || nodes.slice(4,66).filter(n => n.classList.contains('swatch')).length !== 49) return null;
  const group = document.createElementNS('http://www.w3.org/2000/svg','g');
  group.setAttribute('class','material-chart');
  parent.insertBefore(group,nodes[4]); group.append(...nodes.slice(4,66));
  const {center:[x,y],translate:[dx,dy],rotation,scale} = registration;
  return {
    set(enabled) {
      if (enabled) group.setAttribute('transform', `translate(${x+dx} ${y+dy}) rotate(${rotation}) scale(${scale}) translate(${-x} ${-y})`);
      else group.removeAttribute('transform');
      group.dataset.aligned = String(enabled);
    }
  };
}
